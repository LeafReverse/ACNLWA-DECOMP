#!/usr/bin/env python3
import argparse
import concurrent.futures
import os
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from ctrproject import LoadBinary, LoadProject, ProjectPath, ReadSplits, ReadSymbols, ToolPath

LINK_DIR = ProjectPath("build", "link")
OBJECT_DIR = LINK_DIR / "obj"
ASM_DIR = ProjectPath("build", "asm")
ELF_PATH = LINK_DIR / "acnlwa.axf"
DECLARATION = re.compile(r"^\s+(EXPORT|EXTERN)\s+\|(.+)\|\s*$")
LABEL_ADDRESS = re.compile(r"^lbl_([0-9A-Fa-f]{8})$")
GAP_LINE_BYTES = 16
GAP_FILE_BYTES = 0x30000
SHADOWED_BASE = 0x10000000
ASFLAGS = ["--cpu=MPCore", "--apcs=/interwork"]
LINKFLAGS = ["--cpu=MPCore", "--sort=lexical", "--no_remove", "--noscanlib", "--entry=0x100000"]
HEADER = "; generated by tools/relink.py, armasm syntax\n    PRESERVE8\n"

def emittedRanges(units, functions):
    import bisect
    starts = [s.Addr for s in functions]
    ranges = []
    for unit in units:
        for section, start, end in unit.Ranges:
            if section != ".text": continue

            for sym in functions[bisect.bisect_left(starts, start):bisect.bisect_left(starts, end)]:
                if "linker" in sym.Attrs: continue

                length = min(sym.Size, end - sym.Addr)
                if length > 0: ranges.append((sym.Addr, sym.Addr + length, unit.Name, sym.Name))

    return sorted(ranges)

def splitShadowed(ranges):
    placed, shadowed = [], []
    for item in ranges:
        if placed and item[0] < placed[-1][1]:
            shadowed.append(item)
            continue

        placed.append(item)

    for start, end, unit, name in shadowed: print("warning: %s [%08X-%08X] in %s starts inside the previous function; linked outside the image" % (name, start, end, unit), file=sys.stderr)

    return placed, shadowed

def textGaps(ranges, text):
    gaps = []
    cursor = text.Addr
    for start, end, _, _ in ranges:
        if start > cursor: gaps.append((cursor, start))

        cursor = max(cursor, end)

    if cursor < text.End: gaps.append((cursor, text.End))

    return gaps

def renderGaps(binary, gaps):
    files = []
    lines = [HEADER]
    size = 0
    for start, end in gaps:
        if size >= GAP_FILE_BYTES:
            files.append("\n".join(lines + ["", "    END"]) + "\n")
            lines = [HEADER]
            size = 0

        data = binary.Read(start, end - start)
        lines += ["", "    AREA |t.%08X|, CODE, READONLY, ALIGN=0" % start]
        for offset in range(0, len(data), GAP_LINE_BYTES):
            lines.append("    DCB " + ", ".join("0x%02X" % b for b in data[offset:offset + GAP_LINE_BYTES]))

        size += len(data)

    files.append("\n".join(lines + ["", "    END"]) + "\n")

    return files

def renderSegments(segments):
    lines = [HEADER]
    for seg in segments:
        if seg.Kind == "code": continue

        if seg.Kind == "bss":
            lines += ["", "    AREA |seg.%s|, DATA, NOINIT, ALIGN=2" % seg.Name.lstrip("."), "    SPACE 0x%X" % seg.Size]
            continue

        access = "READONLY" if seg.Kind == "rodata" else "READWRITE"
        lines += ["", "    AREA |seg.%s|, DATA, %s, ALIGN=2" % (seg.Name.lstrip("."), access), "    INCBIN build/link/%s.bin" % seg.Name.lstrip(".")]

    return "\n".join(lines + ["", "    END"]) + "\n"

def declaredNames():
    exported, referenced = set(), set()
    for path in ASM_DIR.rglob("*.s"):
        for line in path.read_text().splitlines():
            match = DECLARATION.match(line)
            if not match: continue

            (exported if match.group(1) == "EXPORT" else referenced).add(match.group(2))

    return exported, referenced

def renderAbsolutes(symbols, exported, referenced):
    byName = {s.Name: s for s in symbols}
    lines = [HEADER]
    missing = []
    for name in sorted(referenced - exported):
        sym = byName.get(name)
        label = LABEL_ADDRESS.match(name)
        if sym: value = sym.Addr | (1 if sym.Kind == "function" and sym.Thumb else 0)
        elif label: value = int(label.group(1), 16)
        else:
            missing.append(name)
            continue

        kind = ("THUMB" if sym.Thumb else "ARM") if sym and sym.Kind == "function" else None
        lines += ["    EXPORT |%s|" % name, "|%s| EQU 0x%08X%s" % (name, value & ~1 if kind == "THUMB" else value, ", " + kind if kind else "")]

    if missing: sys.exit("referenced but unknown symbols: %s" % ", ".join(missing[:20]))

    return "\n".join(lines + ["", "    END"]) + "\n"

def alignedGroups(starts):
    groups = []
    for start in sorted(starts):
        if not groups or start % 4 == 0: groups.append([])

        groups[-1].append(start)

    return groups

def renderScatter(segments, starts):
    lines = []
    for seg in segments:
        if seg.Kind == "bss": continue

        name = seg.Name.lstrip(".").upper()
        lines += ["LR_%s 0x%08X" % (name, seg.Addr), "{"]
        if seg.Kind == "code":
            for group in alignedGroups(starts): lines += ["    ER_%08X 0x%08X FIXED" % (group[0], group[0]), "    {"] + ["        *(t.%08X)" % start for start in group] + ["    }"]
        else: lines += ["    ER_%s 0x%08X FIXED" % (name, seg.Addr), "    {", "        *(seg.%s)" % seg.Name.lstrip("."), "    }"]

        bss = next((s for s in segments if s.Kind == "bss" and s.Addr == seg.End), None)
        if bss: lines += ["    ER_%s 0x%08X" % (bss.Name.lstrip(".").upper(), bss.Addr), "    {", "        *(seg.%s)" % bss.Name.lstrip("."), "    }"]

        lines.append("}")

    lines += ["LR_SHADOWED 0x%08X" % SHADOWED_BASE, "{", "    ER_SHADOWED 0x%08X" % SHADOWED_BASE, "    {", "        *(s.*)", "        *(i.*)", "    }", "}"]

    return "\n".join(lines) + "\n"

def renameMaps(units, ranges, shadowed):
    maps = {unit.Name: [] for unit in units}
    for start, _, unit, name in ranges: maps[unit].append(("i.%s" % name, "t.%08X" % start))

    for start, _, unit, name in shadowed: maps[unit].append(("i.%s" % name, "s.%08X" % start))

    return maps

def writeIfChanged(path, content):
    data = content.encode() if isinstance(content, str) else content
    if path.exists() and path.read_bytes() == data: return

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)

def Generate():
    binary = LoadBinary(LoadProject())
    symbols = ReadSymbols()
    units = ReadSplits()
    functions = sorted((s for s in symbols if s.Kind == "function" and s.Section == ".text"), key=lambda s: s.Addr)
    text = next(s for s in binary.Segments if s.Kind == "code")
    ranges, shadowed = splitShadowed(emittedRanges(units, functions))
    gaps = textGaps(ranges, text)
    exported, referenced = declaredNames()
    for seg in binary.Segments:
        if seg.Kind not in ("code", "bss"): writeIfChanged(LINK_DIR / ("%s.bin" % seg.Name.lstrip(".")), binary.Read(seg.Addr, seg.Size))

    gapFiles = renderGaps(binary, gaps)
    for index, content in enumerate(gapFiles): writeIfChanged(LINK_DIR / ("gaps_%02d.s" % index), content)

    for stale in LINK_DIR.glob("gaps_*.s"):
        if int(stale.stem.split("_")[1]) >= len(gapFiles): stale.unlink()

    writeIfChanged(LINK_DIR / "segments.s", renderSegments(binary.Segments))
    writeIfChanged(LINK_DIR / "absolute.s", renderAbsolutes(symbols, exported, referenced))
    writeIfChanged(LINK_DIR / "scatter.sct", renderScatter(binary.Segments, [start for start, _, _, _ in ranges] + [start for start, _ in gaps]))
    sources = ["gaps_%02d" % index for index in range(len(gapFiles))] + ["segments", "absolute"]
    maps = renameMaps(units, ranges, shadowed)
    objects = ["build/link/obj/%s.o" % name for name in sorted(maps)] + ["build/link/%s.o" % name for name in sources]
    writeIfChanged(LINK_DIR / "objects.via", "\n".join(objects) + "\n")
    print("%d functions (%d bytes) + %d gaps (%d bytes) in .text, %d absolute symbols" % (len(ranges), sum(e - s for s, e, _, _ in ranges), len(gaps), sum(e - s for s, e in gaps), len(referenced - exported)))

    return sources, maps

def run(command, env=None):
    result = subprocess.run(command, capture_output=True, text=True, env=env)
    return result.returncode, (result.stdout + result.stderr).strip()

def compileTool(program, args):
    return [sys.executable, str(ProjectPath("tools", "cc.py")), program] + args

def Prepare(sources, maps, jobs):
    objcopy = str(ToolPath("arm-none-eabi", "objcopy"))
    jobsList = [compileTool("armasm", ASFLAGS + ["build/link/%s.s" % name, "-o", "build/link/%s.o" % name]) for name in sources]
    for unit, renames in maps.items():
        output = OBJECT_DIR / ("%s.o" % unit)
        output.parent.mkdir(parents=True, exist_ok=True)
        jobsList.append([objcopy] + sum((["--rename-section", "%s=%s" % pair] for pair in renames), []) + [str(ProjectPath("build", "target", "%s.o" % unit)), str(output)])

    with concurrent.futures.ThreadPoolExecutor(max_workers=jobs or os.cpu_count()) as pool:
        failures = [(command, text) for command, (code, text) in zip(jobsList, pool.map(run, jobsList)) if code]

    if failures: sys.exit("%d preparation step(s) failed, first: %s\n%s" % (len(failures), " ".join(failures[0][0][-3:]), failures[0][1]))

def Link():
    code, text = run(compileTool("armlink", LINKFLAGS + ["--scatter=build/link/scatter.sct", "--map", "--list=build/link/acnlwa.map", "--output=build/link/acnlwa.axf", "--via=build/link/objects.via"]))
    errors = [line for line in text.splitlines() if "Error:" in line]
    if code or errors: sys.exit("armlink failed (%d errors):\n%s" % (len(errors), "\n".join((errors or text.splitlines())[:20])))

def rebuiltImage(elfPath, segments, size):
    from elftools.elf.elffile import ELFFile
    image = bytearray(size)
    with open(elfPath, "rb") as fh:
        for segment in ELFFile(fh).iter_segments():
            if segment["p_type"] != "PT_LOAD" or not segment["p_filesz"] or segment["p_vaddr"] >= SHADOWED_BASE: continue

            target = next((s for s in segments if s.Addr <= segment["p_vaddr"] < s.End), None)
            if target is None or target.Offset is None: sys.exit("segment at 0x%08X is outside the original image" % segment["p_vaddr"])

            start = target.Offset + segment["p_vaddr"] - target.Addr
            image[start:start + segment["p_filesz"]] = segment.data()

    return bytes(image)

def Verify(elfPath, output):
    binary = LoadBinary(LoadProject())
    rebuilt = rebuiltImage(elfPath, binary.Segments, len(binary.Data))
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(rebuilt)
    if rebuilt != binary.Data:
        first = next(i for i, (a, b) in enumerate(zip(rebuilt, binary.Data)) if a != b)
        seg = next((s for s in binary.Segments if s.Offset is not None and s.Offset <= first < s.Offset + s.Size), None)
        where = "0x%08X" % (seg.Addr + first - seg.Offset) if seg else "file offset 0x%X" % first
        count = sum(1 for a, b in zip(rebuilt, binary.Data) if a != b)
        sys.exit("%s differs from the original: %d bytes, first at %s" % (output, count, where))

    print("%s is byte-identical to the original (%d bytes)" % (output, len(rebuilt)))

def main():
    parser = argparse.ArgumentParser(description="Relink every target object with armlink at the original addresses (lexical placement, as 3dsdecomp-toolkit does) and check the rebuilt code.bin")
    parser.add_argument("-j", "--jobs", type=int)
    parser.add_argument("--output", default=str(LINK_DIR / "code.bin"))
    args = parser.parse_args()
    sources, maps = Generate()
    Prepare(sources, maps, args.jobs)
    Link()
    Verify(ELF_PATH, Path(args.output))

if __name__ == "__main__":
    main()
